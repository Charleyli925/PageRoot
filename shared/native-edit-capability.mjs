const DEDICATED_EDITOR_ROOTS = new Set([
  "input",
  "button",
  "textarea",
  "select",
  "option",
  "script",
  "style",
  "template",
  "title",
  "canvas",
  "audio",
  "video",
  "object",
  "embed",
  "iframe",
  "svg",
  "math",
  "pre",
  "code",
]);

const NON_TEXT_ISLAND_ROOTS = new Set([
  ...DEDICATED_EDITOR_ROOTS,
  "html",
  "head",
  "body",
  "base",
  "link",
  "meta",
  "area",
  "br",
  "col",
  "hr",
  "img",
  "param",
  "source",
  "track",
  "wbr",
  "table",
  "thead",
  "tbody",
  "tfoot",
  "tr",
  "colgroup",
  "ul",
  "ol",
  "menu",
  "dl",
  "form",
  "fieldset",
  "datalist",
  "details",
]);

export function isNativeDirectEditRoot(tagName) {
  const normalized = String(tagName ?? "").toLowerCase();
  return Boolean(normalized) && !NON_TEXT_ISLAND_ROOTS.has(normalized);
}
